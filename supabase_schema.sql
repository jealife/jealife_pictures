-- 5. MEDIA_TOPICS (Join Table)
create table public.media_topics (
  media_id bigint references public.media(id) on delete cascade not null,
  topic_id bigint references public.topics(id) on delete cascade not null,
  created_at timestamp with time zone default timezone('utc'::text, now()) not null,
  primary key (media_id, topic_id)
);

alter table public.media_topics enable row level security;

create policy "Media topics are viewable by everyone." 
  on public.media_topics for select using (true);

-- 6. LIKES
create table public.media_likes (
  user_id uuid references auth.users not null,
  media_id bigint references public.media(id) on delete cascade not null,
  created_at timestamp with time zone default timezone('utc'::text, now()) not null,
  primary key (user_id, media_id)
);

alter table public.media_likes enable row level security;

create policy "Likes are viewable by everyone." 
  on public.media_likes for select using (true);

create policy "Users can like media (insert)." 
  on public.media_likes for insert with check (auth.uid() = user_id);

create policy "Users can unlike media (delete)." 
  on public.media_likes for delete using (auth.uid() = user_id);

-- Function to increment/decrement likes_count on media when like is added/removed
create or replace function public.handle_new_like()
returns trigger as $$
begin
  update public.media
  set likes_count = likes_count + 1
  where id = new.media_id;
  return new;
end;
$$ language plpgsql;

create trigger on_like_added
  after insert on public.media_likes
  for each row execute procedure public.handle_new_like();

create or replace function public.handle_unlike()
returns trigger as $$
begin
  update public.media
  set likes_count = likes_count - 1
  where id = old.media_id;
  return old;
end;
$$ language plpgsql;

create trigger on_like_removed
  after delete on public.media_likes
  for each row execute procedure public.handle_unlike();

-- 7. COLLECTIONS (User created albums)
create table public.collections (
  id bigint generated by default as identity primary key,
  user_id uuid references public.profiles(id) not null,
  title text not null,
  description text,
  is_private boolean default false,
  created_at timestamp with time zone default timezone('utc'::text, now()) not null,
  updated_at timestamp with time zone default timezone('utc'::text, now()) not null
);

alter table public.collections enable row level security;

create policy "Public collections are viewable by everyone." 
  on public.collections for select using (is_private = false);

create policy "Users can view their own private collections." 
  on public.collections for select using (auth.uid() = user_id);

create policy "Users can create collections." 
  on public.collections for insert with check (auth.uid() = user_id);

create policy "Users can update their own collections." 
  on public.collections for update using (auth.uid() = user_id);

create policy "Users can delete their own collections." 
  on public.collections for delete using (auth.uid() = user_id);

-- Collection Items
create table public.collection_media (
  collection_id bigint references public.collections(id) on delete cascade not null,
  media_id bigint references public.media(id) on delete cascade not null,
  added_at timestamp with time zone default timezone('utc'::text, now()) not null,
  primary key (collection_id, media_id)
);

alter table public.collection_media enable row level security;

create policy "Public collection items are viewable." 
  on public.collection_media for select 
  using (exists (
    select 1 from public.collections 
    where id = public.collection_media.collection_id and is_private = false
  ));

create policy "Users can manage items in their collections."
  on public.collection_media for all
  using (exists (
    select 1 from public.collections 
    where id = public.collection_media.collection_id and user_id = auth.uid()
  ));


